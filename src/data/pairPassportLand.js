/* ------------------------------------------------------------------------- */
/*  Dot-matrix generation (runs once, then cached)                           */
/* ------------------------------------------------------------------------- */

const DOT_STEP = 7; // spacing between dots, in map units (1000 wide)

const polygonBoxes = LAND_POLYGONS.map((poly) => {
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  for (const [x, y] of poly) {
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  }
  return { minX, maxX, minY, maxY };
});

function inPolygon(lon, lat, poly) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

function isLand(lon, lat) {
  for (let p = 0; p < LAND_POLYGONS.length; p++) {
    const b = polygonBoxes[p];
    if (lon < b.minX || lon > b.maxX || lat < b.minY || lat > b.maxY) continue;
    if (inPolygon(lon, lat, LAND_POLYGONS[p])) return true;
  }
  return false;
}

let cachedPath = null;

/**
 * Returns one SVG path string made of zero-length segments. Drawn with a round
 * line-cap, each segment becomes a dot — so the whole land mass is ONE element.
 */
export function getLandDotPath() {
  if (cachedPath) return cachedPath;
  const { w, h } = MAP_VIEW;
  const { lonMin, lonMax, latMax, latMin } = MAP_BOUNDS;
  let d = "";
  let row = 0;
  for (let y = DOT_STEP / 2; y < h; y += DOT_STEP, row++) {
    const offset = row % 2 ? DOT_STEP / 2 : 0;
    for (let x = DOT_STEP / 2 + offset; x < w; x += DOT_STEP) {
      const lon = lonMin + (x / w) * (lonMax - lonMin);
      const lat = latMax - (y / h) * (latMax - latMin);
      if (isLand(lon, lat)) d += `M${x.toFixed(1)} ${y.toFixed(1)}h.01`;
    }
  }
  cachedPath = d;
  return d;
}
